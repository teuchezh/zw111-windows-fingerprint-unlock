#!/usr/bin/env python3
"""Converts assets/icon-1024.png into credprov/tile_icon.h: 128x128 premultiplied BGRA pixels for the sign-in tile.

Run after changing the icon:  python3 windows/tools/make_tile_header.py
"""
import os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'assets', 'icon-1024.png')
dst = os.path.join(here, '..', 'credprov', 'tile_icon.h')
N = 128

im = Image.open(src).convert('RGBA').resize((N, N), Image.LANCZOS)
out = bytearray()
for r, g, b, a in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()):
    out += bytes((b * a // 255, g * a // 255, r * a // 255, a))   # premultiplied BGRA, top-down

with open(dst, 'w') as f:
    f.write('// Generated by windows/tools/make_tile_header.py from assets/icon-1024.png. Do not edit.\n')
    f.write('#pragma once\n#define ZW_TILE_ICON_SIZE %d\n' % N)
    f.write('static const unsigned char kTileIconBgra[%d] = {\n' % len(out))
    for i in range(0, len(out), 24):
        f.write('  ' + ','.join(str(x) for x in out[i:i + 24]) + ',\n')
    f.write('};\n')
print('wrote', dst, len(out), 'bytes')
