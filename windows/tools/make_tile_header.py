#!/usr/bin/env python3
"""Converts assets/tile-glyph-256.png into credprov/tile_icon.h for the sign-in tile:

* kTilePng      - the PNG itself, returned by ICredentialProviderCredential3::GetBitmapBufferValue
                  (Windows 11 LogonUI keeps the transparency on this path);
* kTileIconBgra - 128x128 premultiplied BGRA for the classic HBITMAP path (older Windows).

Run after changing the glyph:  python3 windows/tools/make_tile_header.py
"""
import io, os
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'assets', 'tile-glyph-256.png')
dst = os.path.join(here, '..', 'credprov', 'tile_icon.h')
N = 128

im = Image.open(src).convert('RGBA')
png = io.BytesIO(); im.save(png, 'PNG', optimize=True); png = png.getvalue()
small = im.resize((N, N), Image.LANCZOS)
pixels = small.get_flattened_data() if hasattr(small, 'get_flattened_data') else small.getdata()
bgra = bytearray()
for r, g, b, a in pixels:
    bgra += bytes((b * a // 255, g * a // 255, r * a // 255, a))   # premultiplied BGRA, top-down

def arr(name, data):
    out = 'static const unsigned char %s[%d] = {\n' % (name, len(data))
    for i in range(0, len(data), 24):
        out += '  ' + ','.join(str(x) for x in data[i:i + 24]) + ',\n'
    return out + '};\n'

with open(dst, 'w') as f:
    f.write('// Generated by windows/tools/make_tile_header.py from assets/tile-glyph-256.png. Do not edit.\n')
    f.write('#pragma once\n#define ZW_TILE_ICON_SIZE %d\n' % N)
    f.write(arr('kTilePng', png))
    f.write(arr('kTileIconBgra', bgra))
print('wrote', dst, '| png', len(png), 'bytes, bgra', len(bgra), 'bytes')
